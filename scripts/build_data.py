#!/usr/bin/env python3
"""Merge the lossless Excel import with researched links and produce browser data."""

import argparse
import json
from collections import Counter
from pathlib import Path
from urllib.parse import urlencode, urlsplit

ROOT = Path(__file__).resolve().parents[1]
CATEGORIES = {"カフェ編": "cafe", "人気スイーツ": "sweets", "喫茶店編": "kissaten"}


def build():
    source = json.loads((ROOT / "data/source-shops.json").read_text())
    research = json.loads((ROOT / "data/enrichment.json").read_text())
    ids = {shop["id"] for shop in source}
    if len(ids) != len(source) or ids != set(research):
        raise ValueError("Every source row must have exactly one research record")
    shops = []
    for row in source:
        extra = research[row["id"]]
        shop = {**row, **extra, "kind": CATEGORIES[row["category"]]}
        query = " ".join([row["name"], extra["address"] or "東京都 " + row["ward"] + " " + row["neighborhood"]])
        shop["mapUrl"] = extra.get("mapUrl") or "https://www.google.com/maps/search/?" + urlencode({"api": "1", "query": query})
        shop["mapType"] = "place" if extra.get("mapUrl") else "name-and-address-search"
        shop["checkedAt"] = "2026-10-11"
        shop["infoUrl"] = extra["officialUrl"] or extra["sourceUrl"]
        for key in ["officialUrl", "sourceUrl", "mapUrl", "infoUrl"]:
            url = shop.get(key)
            if url and (urlsplit(url).scheme not in {"https", "http"} or not urlsplit(url).netloc):
                raise ValueError(f"Invalid {key} for {row['name']}")
        if bool(shop["officialUrl"]) == (shop["linkType"] == "unconfirmed"):
            raise ValueError(f"Link label does not match official source for {row['name']}")
        shops.append(shop)
    if len(shops) != 69:
        raise ValueError(f"Expected 69 catalogue shops, found {len(shops)}")
    dataset = {"updatedAt": "2026-10-11", "total": len(shops), "districts": len({s["ward"] for s in shops}), "shops": shops}
    return dataset


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Check that committed browser data matches source")
    args = parser.parse_args()
    dataset = build()
    encoded = json.dumps(dataset, ensure_ascii=False, indent=2) + "\n"
    javascript = "// Generated by scripts/build_data.py. Edit data/enrichment.json instead.\nwindow.CAFE_DATA = " + encoded.rstrip() + ";\n"
    outputs = {ROOT / "data/shops.json": encoded, ROOT / "shops.js": javascript}
    for path, contents in outputs.items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != contents:
                raise SystemExit(f"Outdated generated data: {path.relative_to(ROOT)}")
        else:
            path.write_text(contents, encoding="utf-8")
    print(f"{'Verified' if args.check else 'Built'} {dataset['total']} shops / {dataset['districts']} districts")
    print("Link types:", dict(Counter(s["linkType"] for s in dataset["shops"])))


if __name__ == "__main__":
    main()
